import { defineConfig, type Plugin } from 'vite'

/**
 * Комментарии в шейдерах — в исходник, а не в бандл.
 *
 * GLSL здесь живёт внутри шаблонных строк TypeScript, размеченных
 * `/* glsl *\/`. Для минификатора это не код, а содержимое строки, и он не
 * трогает в нём ничего: все объяснения — почему земля считается
 * отражённым светом, почему сетка звёзд угловая, где заканчивается
 * Preetham — уезжают посетителю байт в байт. Замер на 2026-08-10:
 * 17.7 КБ шейдерного текста, из них 11.1 КБ (63 %) — комментарии.
 *
 * Убирать их из исходника нельзя: там они и нужны, это единственное
 * место, где видно причину каждой строки шейдера. Поэтому они снимаются
 * на сборке. В деве трансформ не работает — там в отладчике удобнее
 * видеть шейдер целиком, вместе с рассуждением.
 *
 * Строк в GLSL не бывает, поэтому `//` и `/* *\/` внутри блока не могут
 * оказаться ничем, кроме комментария, и разбор регуляркой здесь
 * безопасен — в отличие от такого же разбора обычного кода.
 */
function stripShaderComments(): Plugin {
  return {
    name: 'strip-shader-comments',
    apply: 'build',
    enforce: 'pre',
    transform(code, id) {
      if (!/\.tsx?$/.test(id) || !code.includes('/* glsl */')) return null
      let changed = false
      const out = code.replace(/\/\* glsl \*\/ `([\s\S]*?)`/g, (whole, body: string) => {
        const lean = body
          // Блочный комментарий заменяется переводом строки, а не пустотой:
          // если он когда-нибудь окажется посреди строки кода, соседние
          // токены не должны склеиться в один.
          .replace(/\/\*[\s\S]*?\*\//g, '\n')
          .split('\n')
          .map((line) => line.replace(/\/\/.*$/, '').trimEnd())
          .filter((line) => line.trim().length > 0)
          .join('\n')
        if (lean === body) return whole
        changed = true
        return `/* glsl */ \`${lean}\``
      })
      return changed ? { code: out, map: null } : null
    },
  }
}

export default defineConfig({
  plugins: [stripShaderComments()],
  server: {
    // Порт берётся из окружения, если он там задан. Инструменты, которые
    // поднимают дев-сервер за нас, выдают порт через PORT и ожидают, что
    // мы его послушаем; прибитый гвоздями 5178 в этом случае просто
    // сталкивается с чужим сервером в той же папке.
    port: process.env.PORT ? Number(process.env.PORT) : 5178,
  },
})
