import { coarsePointer, currentMode, roomCapable, setMode } from './lobby'
import { mountContent } from './page/mount'

/**
 * Точка входа. Единственная её работа — решить, грузить ли комнату.
 *
 * Импорт `./main` динамический, и это не стилистика: у него в зависимостях
 * three.js. Статический импорт затащил бы 300 КБ в бандл первой загрузки
 * даже тому посетителю, которому сцену не покажут. С динамическим Vite
 * выносит сцену в отдельный чанк, и телефон скачивает страницу, а не
 * рендерер.
 */

let roomModule: Promise<unknown> | null = null

/**
 * Позиция скролла страницы на момент входа в комнату.
 *
 * В комнате `html, body` схлопываются в `height: 100%; overflow: hidden`
 * (см. index.html) — документ перестаёт быть длиннее экрана, и браузер
 * зажимает `scrollY` в ноль сам, без нашего участия. Обратно это значение
 * никто не помнит: возврат `overflow: auto` восстанавливает СВОЙСТВО, а не
 * прежнюю позицию. Поэтому запоминаем её здесь, до `setMode('room')`, и
 * возвращаем вручную в `leaveRoom()` — иначе посетитель, долиставший
 * страницу до середины и заглянувший в комнату, откатывался бы в начало.
 */
let scrollBeforeRoom = 0

/**
 * Порядок обязателен, и это не тюнинг.
 *
 * `EffectComposer` снимает размер холста в конструкторе, а `main.ts`
 * исполняется целиком на импорте. Импортировать модуль раньше, чем холст
 * получил настоящий размер, значит собрать всю пост-цепочку по размеру
 * 300 × 150 — это дефолт canvas, и CSS его потом просто растянет.
 */
export async function enterRoom() {
  const button = document.getElementById('enter-room') as HTMLButtonElement | null
  const note = document.getElementById('enter-failed')
  // Отказ от прошлой попытки прячется В НАЧАЛЕ каждой новой: иначе после
  // сорвавшейся загрузки и удавшейся следующей посетитель уходил бы в
  // комнату с висящим на странице «комната не загрузилась».
  if (note) note.hidden = true
  if (button) button.disabled = true
  // Читаем ДО setMode: после него документ уже схлопнут, и scrollY — уже 0.
  scrollBeforeRoom = window.scrollY
  setMode('room')
  // Два кадра: первый отдаёт раскладке новый display, второй гарантирует,
  // что clientWidth уже посчитан.
  await new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)))
  try {
    // Промис запоминается ДО `await`, а не после успеха: пока чанк едет,
    // второй тап обязан присоединиться к тому же импорту, а не завести
    // рядом второй. Повторяемость даёт не порядок присваивания, а СБРОС В
    // `catch` ниже: при обрыве трёхсот килобайт `roomModule` снимается в
    // null, и следующий тап пробует заново, а не молча ничего не делает.
    roomModule ??= import('./main')
    await roomModule
    // ФОКУС ПЕРЕЕЗЖАЕТ В КОМНАТУ, и это не вежливость, а исправление.
    //
    // Обход клавишей Tab продолжается с того места, где стоял последний
    // сфокусированный элемент, — а кнопка входа лежит в разметке ПОСЛЕ
    // предметов комнаты. Значит вошедший по кнопке первым же Tab уезжал
    // мимо всех шести предметов прямо в скрытый текст страницы. Сама
    // кнопка к этому моменту уже спрятана, но точку отсчёта браузер
    // держит там, где она была.
    //
    // Поймано на iPad и только на нём: на десктопе комната открывается
    // сама, фокус стоит в начале документа, и ошибки не видно вовсе.
    //
    // Контейнер, а не первая кнопка: вставать сразу на предмет — значит
    // показать обвод тому, кто про клавиатуру ничего не спрашивал.
    // `tabindex="-1"` делает его целью для focus(), но не для Tab.
    document.getElementById('hotspot-buttons')?.focus({ preventScroll: true })
  } catch (err) {
    roomModule = null
    setMode('page')
    if (note) note.hidden = false
    console.warn('[room] не загрузилась', err)
  } finally {
    if (button) button.disabled = false
  }
}

export function leaveRoom() {
  setMode('page')
  // Фокус возвращается туда, откуда уходил, — на кнопку входа. Вышедший
  // крестиком иначе остался бы с фокусом на элементе, которого больше не
  // видно, и следующий Tab начался бы с середины страницы.
  document.getElementById('enter-room')?.focus({ preventScroll: true })
  // `overflow: auto` возвращается в раскладку не мгновенно — до пересчёта
  // стилей документ всё ещё схлопнут, и scrollTo сейчас же просто зажмётся
  // обратно в 0 той же логикой, что и при входе. Кадр вперёд гарантирует,
  // что раскладка уже применилась и документ снова длиннее экрана.
  requestAnimationFrame(() => window.scrollTo(0, scrollBeforeRoom))
}

function decide() {
  // Ширина больше не решает всё: на телефоне комната открывается по
  // кнопке, а не потому, что окно широкое.
  if (roomCapable()) void enterRoom()
  else setMode('page')
}

decide()

// Одно дерево контента на оба режима: в комнате оно скрыто за холстом и
// нужно поисковику со скринридером, на телефоне это и есть страница.
// Какое из двух — решает CSS по data-mode, а не этот вызов.
mountContent()

/**
 * Окно меняет размер — гейт пересматривается в обе стороны, и правило у
 * него одно на оба направления:
 *
 * **НА КАСАНИИ ГЕЙТ КОМНАТУ НЕ ЗАКРЫВАЕТ НИКОГДА. НА УКАЗАТЕЛЕ-МЫШИ ОН
 * ВЛАДЕЕТ РЕЖИМОМ ВСЕГДА.**
 *
 * Почему палец вынесен отдельной проверкой, а не отдан `roomCapable()`
 * целиком: на пальце `roomCapable()` ложна ВСЕГДА (это её первая строка), а
 * `resize` прилетает на каждый поворот экрана и на каждое сворачивание
 * адресной строки. Закрывать комнату по такому событию значит выкидывать
 * человека из неё ровно тогда, когда он послушался карточки «поверни
 * телефон». Поэтому на касании выход только руками — крестиком, который
 * там и показан.
 *
 * На указателе-мыши наоборот: крестика нет (комната там и есть сайт, в неё
 * не «входили»), поэтому гейт обязан быть единственным и полным хозяином
 * режима. Условия «а как он сюда попал» тут быть не должно: комната,
 * открытая любым путём — автовходом, кнопкой на узком окне, догрузкой при
 * растягивании, — на неспособном размере не выживает. Иначе получается
 * комната без выхода, и до этой волны её не было.
 *
 * Растягивание: комнату надо догрузить, но чанк едет только один раз —
 * `roomModule` помнит, что он уже поехал. Разбором сцены возврат не
 * занимается: `leaveRoom()` только переключает режим, и второго писателя
 * `data-mode` это не заводит — функция та же самая, что у крестика.
 */
addEventListener('resize', () => {
  if (roomModule) {
    if (currentMode() === 'room' && !coarsePointer() && !roomCapable()) leaveRoom()
    return
  }
  if (currentMode() === 'page' && roomCapable()) void enterRoom()
})

const enter = document.getElementById('enter-room')
if (enter) {
  enter.hidden = false
  enter.addEventListener('click', () => void enterRoom())
}

const leave = document.getElementById('leave-room')
// Крестик живёт в разметке страницы, а не в main.ts: если WebGL недоступен,
// main.ts бросит на верхнем уровне, и выход обязан существовать всё равно.
if (leave) leave.addEventListener('click', () => leaveRoom())
