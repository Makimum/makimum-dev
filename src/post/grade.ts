import * as THREE from 'three'

/**
 * Финальная цветокоррекция одним проходом: виньетка, зерно,
 * хроматическая аберрация по краям и лёгкий лифт теней.
 *
 * Все четыре эффекта живут в ОДНОМ шейдере, а не в четырёх пассах.
 * Каждый лишний ShaderPass — это ещё один полноэкранный рендер-таргет,
 * а на ультрашироком мониторе они стоят сотни мегабайт. На машине,
 * которая и так живёт в свопе, это решающая экономия.
 *
 * Что именно чинит этот проход: запечённая картинка выходит слишком
 * «чистой» — равномерно освещённой от края до края, без единого
 * артефакта. Глаз читает такое как ненастоящее, потому что настоящая
 * оптика так не умеет. Виньетка и аберрация возвращают объектив,
 * зерно — плёнку, лифт теней — то, что в реальной тени никогда
 * не бывает абсолютно чёрных пикселей.
 */

export const GradeShader = {
  name: 'GradeShader',

  uniforms: {
    tDiffuse: { value: null as THREE.Texture | null },
    /** Глубина сцены из отдельного прохода — см. composer.ts. */
    tDepth: { value: null as THREE.Texture | null },
    uTime: { value: 0 },
    /** Размер пикселя буфера. Именно буфера, а не CSS: радиус расфокуса
     *  задаётся в пикселях, и на DPR 1.5 CSS-пиксель врал бы в полтора раза. */
    uTexel: { value: new THREE.Vector2(1 / 1920, 1 / 1080) },
    /** Плоскости камеры — без них глубина не разворачивается в метры. */
    uNear: { value: 0.05 },
    uFar: { value: 60 },
    /** Расстояние до точки фокуса, метры. Это цель орбиты: то, на что
     *  человек смотрит, и есть то, что должно быть резким. */
    uFocus: { value: 3 },
    /** Полуширина полностью резкой зоны, метры. */
    uFocusRange: { value: 0.3 },
    /**
     * Круг нерезкости в пикселях: ближе фокуса и дальше него.
     *
     * Подобрано на живой комнате. Обещанные в спеке 2.8 и 3.6 на деле не
     * читались вовсе — комната глубиной три метра, и на таком коротком
     * плане размытие в три пикселя неотличимо от резкости. 22 для проверки
     * работоспособности превращали кадр в макро. Пять и шесть с половиной —
     * та середина, где расфокус чувствуется, но не замечается: кресло
     * держит резкость, окно и батарея уходят мягко.
     */
    uCocNear: { value: 5.0 },
    uCocFar: { value: 6.5 },
    /** Сила виньетки, 0..1 */
    uVignette: { value: 0.5 },
    /** Зерно, 0..1 */
    uGrain: { value: 0.05 },
    /**
     * Размер зерна в пикселях БУФЕРА.
     *
     * У плёночного зерна есть размер: оно комкается. Раньше зерно клалось
     * по одному отсчёту на пиксель, и на ровной тёмной стене это читалось
     * не как плёнка, а как грязный экран — мелкой правильной рябью.
     * Установлено замером: при uGrain 0 рябь исчезает целиком, при 0.05
     * возвращается, а стены при этом — материал без единой текстуры.
     */
    uGrainCell: { value: 1.35 },
    /** Номер кадра: зерно перебрасывается целиком, а не плывёт. */
    uGrainSeed: { value: 0 },
    /** Контраст вокруг 18% серого. 1 — не трогать. */
    uContrast: { value: 1.12 },
    /**
     * Дизеринг — НЕ зерно, и путать их нельзя.
     *
     * Холст на выходе восьмибитный, а тёмные плавные градиенты (стена,
     * уходящая в тень; ночное небо в проёме) в восемь бит не помещаются:
     * появляются ступени — те самые прерывистые линии, из-за которых кадр
     * выглядит как сломавшийся телевизор. Лечится это подмешиванием шума
     * АМПЛИТУДОЙ В ОДИН МЛАДШИЙ РАЗРЯД: ступень размывается в градиент,
     * который глаз читает как гладкий.
     *
     * Зерно для этого не годится в принципе: у него есть размер ячейки
     * (1.35 px), а дизеринг обязан быть попиксельным — иначе он не
     * разбивает ступень, а рисует поверх неё узор.
     */
    uDither: { value: 0.004 },
    /** Хроматическая аберрация в пикселях на краю кадра */
    uAberration: { value: 1.4 },
    /** Подъём теней: сколько добавить в самых тёмных местах */
    uLift: { value: 0.018 },
    /**
     * Насыщенность: 1 — как есть.
     *
     * Поднята с 1.12: комната собрана из бежево-серых материалов, и на
     * прежнем значении разница между закатом и полуднем в ней почти не
     * проступала — цвет света был, а поверхности его не показывали.
     */
    uSaturation: { value: 1.24 },
    uResolution: { value: new THREE.Vector2(1, 1) },
  },

  vertexShader: /* glsl */ `
    varying vec2 vUv;
    void main() {
      vUv = uv;
      gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
    }
  `,

  fragmentShader: /* glsl */ `
    precision highp float;

    #include <packing>

    uniform sampler2D tDiffuse;
    uniform sampler2D tDepth;
    uniform vec2  uTexel;
    uniform float uNear;
    uniform float uFar;
    uniform float uFocus;
    uniform float uFocusRange;
    uniform float uCocNear;
    uniform float uCocFar;
    uniform float uTime;
    uniform float uVignette;
    uniform float uGrain;
    uniform float uAberration;
    uniform float uLift;
    uniform float uSaturation;
    uniform vec2  uResolution;
    uniform float uGrainCell;
    uniform float uGrainSeed;
    uniform float uContrast;
    uniform float uDither;

    varying vec2 vUv;

    /**
     * Хеш без синуса (Hoskins). Синусный вариант работал, но зависит от
     * величины аргумента: на координатах порядка тысяч он держится только
     * потому, что умножение на 43758 всё перемешивает. Этот не зависит
     * ни от чего и стоит столько же.
     */
    float hash(vec2 p) {
      vec3 p3 = fract(vec3(p.xyx) * 0.1031);
      p3 += dot(p3, p3.yzx + 33.33);
      return fract((p3.x + p3.y) * p3.z);
    }

    void main() {
      vec2 uv = vUv;
      vec2 centered = uv - 0.5;
      // Расстояние от центра кадра — общий множитель для виньетки
      // и аберрации: оба эффекта у настоящего объектива усиливаются
      // строго к краю и отсутствуют в центре.
      float r = length(centered);

      // --- хроматическая аберрация ---
      // Каналы расходятся РАДИАЛЬНО, а не по горизонтали: у линзы
      // дисперсия идёт от оптической оси, поэтому горизонтальный
      // сдвиг сразу читается как дешёвый «глитч-эффект».
      vec2 dir = r > 0.0001 ? centered / r : vec2(0.0);
      vec2 px = dir * (uAberration / uResolution) * r * r * 2.0;
      vec3 col;
      col.r = texture2D(tDiffuse, uv + px).r;
      col.g = texture2D(tDiffuse, uv).g;
      col.b = texture2D(tDiffuse, uv - px).b;

      // --- глубина резкости ---
      //
      // Точка фокуса — цель орбиты камеры, то есть буквально то, на что
      // смотрит посетитель. Так объектив и наводят: не на середину сцены,
      // а на предмет внимания.
      //
      // Глубина приходит отдельным проходом (composer.ts): читать её из
      // таргета, в который этот же проход пишет, нельзя — это чтение и
      // запись одной текстуры, поведение неопределённое.
      float rawDepth = texture2D(tDepth, uv).x;
      float viewZ = perspectiveDepthToViewZ(rawDepth, uNear, uFar);
      float dist = -viewZ;
      float off = abs(dist - uFocus) - uFocusRange;
      // Ближняя и дальняя нерезкость разные, как у настоящего объектива:
      // за фокусом глубина резкости растягивается, перед ним — нет.
      float coc = off <= 0.0
        ? 0.0
        : (dist < uFocus
            ? min(1.0, off / 0.9) * uCocNear
            : min(1.0, off / 2.6) * uCocFar);

      // Восемь отсчётов по диску Пуассона. Ниже четверти пикселя размывать
      // нечего — там отсчёты схлопываются в центральный и только жгут
      // текстурную выборку.
      if (coc > 0.25) {
        vec2 r0 = coc * uTexel;
        vec3 acc = col;
        acc += texture2D(tDiffuse, uv + vec2(-0.326, -0.406) * r0).rgb;
        acc += texture2D(tDiffuse, uv + vec2(-0.840, -0.074) * r0).rgb;
        acc += texture2D(tDiffuse, uv + vec2(-0.696,  0.457) * r0).rgb;
        acc += texture2D(tDiffuse, uv + vec2(-0.203,  0.621) * r0).rgb;
        acc += texture2D(tDiffuse, uv + vec2( 0.962, -0.195) * r0).rgb;
        acc += texture2D(tDiffuse, uv + vec2( 0.473, -0.480) * r0).rgb;
        acc += texture2D(tDiffuse, uv + vec2( 0.519,  0.767) * r0).rgb;
        acc += texture2D(tDiffuse, uv + vec2( 0.185, -0.893) * r0).rgb;
        col = acc / 9.0;
      }

      // --- контрастная кривая ---
      // Степенная кривая вокруг 18% серого — опоры, относительно которой
      // экспонометры и меряют. Стоит ДО тонмаппинга и до всего остального:
      // ACES отдаёт технически верную, но плоскую картинку, а плёнка
      // разводит низы и света сильнее. Опора именно 0.18, а не 0.5:
      // иначе кривая тянет за собой среднюю яркость кадра.
      col = pow(max(col, vec3(0.0)) / 0.18, vec3(uContrast)) * 0.18;

      // --- лифт теней ---
      // В реальной тени нет абсолютно чёрных пикселей: туда всегда
      // попадает рассеянный свет. Поднимаем только низы, света не трогаем.
      float luma = dot(col, vec3(0.2126, 0.7152, 0.0722));
      col += uLift * (1.0 - smoothstep(0.0, 0.35, luma));

      // --- насыщенность ---
      col = mix(vec3(luma), col, uSaturation);

      // --- виньетка ---
      // smoothstep, а не линейное затухание: у линейного виден чёткий
      // край перехода, и он выглядит как наложенная картинка.
      float vig = smoothstep(0.85, 0.28, r);
      col *= mix(1.0, vig, uVignette);

      // --- зерно ---
      // Зерно кладётся ПОСЛЕ виньетки и модулируется яркостью: в светах
      // плёночное зерно почти не видно, а в полутенях заметнее всего.
      //
      // Координата — gl_FragCoord, то есть пиксели БУФЕРА, а не uv * uResolution:
      // uResolution приходит в CSS-пикселях (1440×900 при буфере 2160×1350),
      // и шаг выборки получался дробным. И главное — floor по ячейке:
      // у зерна должен быть размер, иначе это не плёнка, а шум матрицы.
      vec2 gp = floor(gl_FragCoord.xy / uGrainCell) + uGrainSeed;
      float n = hash(gp) - 0.5;
      col += n * uGrain * (0.35 + 0.65 * (1.0 - abs(luma * 2.0 - 1.0)));

      // --- дизеринг ---
      //
      // Последним и ПОПИКСЕЛЬНО. Это не зерно и не украшение: холст
      // восьмибитный, а тёмная стена, уходящая в тень, — плавный градиент,
      // который в восемь бит не помещается. Без дизеринга он ложится
      // ступенями, и кадр читается как сломавшийся телевизор.
      //
      // Треугольное распределение (разность двух независимых значений),
      // а не равномерное: у равномерного дизеринга остаётся заметная
      // корреляция с самой ступенью, и вместо гладкости получается
      // мерцающая кромка на её месте.
      vec2 dp = gl_FragCoord.xy + uGrainSeed * 7.0;
      float d1 = hash(dp);
      float d2 = hash(dp + 19.73);
      col += (d1 - d2) * uDither;

      gl_FragColor = vec4(col, 1.0);
    }
  `,
}
