import * as THREE from 'three'
import { prefersReducedMotion } from '../lib/reducedMotion'

/**
 * Кресло, которое можно раскрутить.
 *
 * Офисное кресло — единственный предмет в комнате, который в жизни
 * крутят просто так, и именно поэтому оно просится под руку. Важна не
 * сама вращалка, а ВЫБЕГ: настоящее кресло не останавливается там, где
 * его отпустили, оно докручивается и затихает. Без выбега это ползунок,
 * а не кресло.
 *
 * Затухание экспоненциальное, с постоянной времени около секунды, плюс
 * порог остановки — иначе кресло бесконечно ползёт на сотых долях
 * градуса и сцена никогда не засыпает.
 */

/** Радиан на пиксель перетаскивания. Полный оборот ≈ 620 px — примерно
 *  ширина кресла в кадре, то есть «протащить через себя» = один оборот. */
const SENSITIVITY = 0.0101

/** За сколько секунд скорость падает в e раз. */
const SPIN_DAMPING = 1.05

/** Ниже этой скорости кресло считается остановившимся, рад/с. */
const SPIN_STOP = 0.02

/** Максимальная скорость выбега: сильный рывок не должен превращать
 *  кресло в вентилятор. */
const SPIN_MAX = 11

/**
 * Толчок с клавиатуры.
 *
 * У нажатия нет ни скорости, ни длины, которые можно было бы измерить, —
 * значит скорость надо СЧИТАТЬ, а не подбирать. При экспоненциальном
 * затухании весь выбег даёт угол `v₀ · τ`, поэтому ровно один оборот — это
 * `2π / SPIN_DAMPING`. Один толчок = один оборот, то же самое, что
 * «протащить кресло через себя» указателем (см. SENSITIVITY: полный оборот
 * ≈ 620 px, примерно ширина кресла в кадре).
 *
 * Заодно выходит вдвое меньше `SPIN_MAX` — то есть заметный толчок, а не
 * рывок до вентилятора.
 */
const NUDGE_SPEED = (Math.PI * 2) / SPIN_DAMPING

/**
 * Насколько кресло поворачивается по нажатию при отключённой анимации.
 *
 * Выбега там нет, а значит толчок скоростью не сработал бы вовсе: клавиша
 * просто перестала бы что-либо делать. Поворот происходит сразу — вращение
 * это управление, а не украшение (та же логика, что в `end()`).
 *
 * Четверть оборота, а не полный: полный вернул бы кресло ровно туда, где
 * оно стояло, и нажатие снова выглядело бы как ничего не делающее.
 */
const NUDGE_STEP_REDUCED = Math.PI / 2

export interface ChairSpin {
  /** Началось перетаскивание. */
  begin(clientX: number): void
  /** Указатель поехал. */
  drag(clientX: number): void
  /** Отпустили — дальше кресло докручивается само. */
  end(): void
  /**
   * Толчок без указателя — с клавиатуры.
   *
   * Не непрерывное вращение по зажатой клавише: раскрутка кресла жестовая
   * по сути, и равномерный ход по клавише был бы ровно той мёртвой
   * механикой, от которой кресло и уводили. Один толчок — один оборот.
   */
  nudge(): void
  update(dtSeconds: number): void
  dragging(): boolean
  /**
   * Сдвинулось ли кресло РАЗОМ, без скорости, — и, значит, заметила ли это
   * карта теней. Флаг сбрасывается читателем, как у лампы.
   *
   * Нужен ровно одному случаю: толчок при отключённой анимации поворачивает
   * кресло мгновенно, скорости после этого нет, и `moving()` честно
   * отвечает «стоит». Без флага кресло повернулось бы вместе со своей
   * старой тенью.
   */
  shadowDirty(): boolean
  /**
   * Едет ли кресло прямо сейчас — под рукой ИЛИ на выбеге.
   *
   * Нужно карте теней: она перерисовывается только когда в комнате
   * что-то сдвинулось, а кресло — единственное, что двигается. По одному
   * `dragging()` тень застыла бы в момент отпускания и досматривала бы
   * выбег неподвижной.
   */
  moving(): boolean
  label(): string
}

export function createChairSpin(scene: THREE.Scene): ChairSpin | null {
  const chair = scene.getObjectByName('chair')
  if (!chair) {
    console.warn('[chair] узел не найден — вращение не поднято')
    return null
  }

  let held = false
  let lastX = 0
  let lastT = 0
  let velocity = 0
  /** Одноразовый флаг мгновенного поворота: см. `shadowDirty()`. */
  let stepped = false

  return {
    begin(clientX) {
      held = true
      lastX = clientX
      lastT = performance.now()
      velocity = 0
    },
    drag(clientX) {
      if (!held) return
      const now = performance.now()
      const dx = clientX - lastX
      const dt = Math.max(1, now - lastT) / 1000
      chair.rotation.y += dx * SENSITIVITY
      // Скорость берётся из ПОСЛЕДНЕГО отрезка, а не усредняется по
      // всему жесту: иначе медленное подведение перед резким рывком
      // съедает бросок, и кресло отпускают — а оно едва ползёт.
      velocity = (dx * SENSITIVITY) / dt
      lastX = clientX
      lastT = now
    },
    end() {
      if (!held) return
      held = false
      // При отключённой анимации выбега нет: кресло стоит там, где
      // отпустили. Вращение остаётся — это управление, а не украшение.
      // Живой ответ, а не снимок на загрузке: настройку включают тогда,
      // когда от движения уже стало плохо.
      if (prefersReducedMotion()) {
        velocity = 0
        return
      }
      // Рывок, сделанный давно, инерции не даёт: если указатель замер
      // перед отпусканием, кресло должно остановиться, а не улететь.
      if (performance.now() - lastT > 90) velocity = 0
      velocity = Math.max(-SPIN_MAX, Math.min(SPIN_MAX, velocity))
    },
    nudge() {
      // Под рукой клавиша не мешает: указатель главнее.
      if (held) return
      if (prefersReducedMotion()) {
        chair.rotation.y += NUDGE_STEP_REDUCED
        stepped = true
        return
      }
      // Направление всегда одно. Знак не от чего взять: у нажатия нет
      // стороны, а заводить две клавиши ради вращения в обе стороны —
      // интерфейс поверх кресла, которое крутят просто так.
      velocity = NUDGE_SPEED
    },
    update(dt) {
      if (held || velocity === 0) return
      chair.rotation.y += velocity * dt
      velocity *= Math.exp(-dt / SPIN_DAMPING)
      if (Math.abs(velocity) < SPIN_STOP) velocity = 0
    },
    dragging: () => held,
    moving: () => held || velocity !== 0,
    shadowDirty() {
      const v = stepped
      stepped = false
      return v
    },
    label: () => 'spin the chair',
  }
}
