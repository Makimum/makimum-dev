/**
 * Порядок, в котором клавиша Tab обходит предметы комнаты: слева направо,
 * как читает глаз.
 *
 * ПРОЕКЦИЯ ПРИХОДИТ СНАРУЖИ, а не считается здесь. Тогда функция остаётся
 * чистой и проверяется прогоном без браузера — а сцену, камеру и габаритные
 * ящики знает тот, у кого они есть.
 *
 * ПОРЯДОК СНИМАЕТСЯ ОДИН РАЗ, в обзорной позе, и дальше не пересчитывается.
 * Соблазн пересчитывать его на каждое движение камеры велик — казалось бы,
 * так «правильнее», обвод всегда идёт по тому, что видно. На деле это даёт
 * Tab, который ведёт то туда, то сюда: посетитель повернул комнату на
 * двадцать градусов, и следующее нажатие уводит его не туда, куда уводило
 * секунду назад. Предсказуемость тут дороже точности — вещи, которые
 * выглядят одинаково, обязаны вести себя одинаково.
 *
 * Позиции самих кнопок за камерой при этом следят; фиксирован ПОРЯДОК, а не
 * координаты.
 */
export function tabOrder<T>(items: T[], screenX: (item: T) => number): T[] {
  // Копия, а не сортировка на месте: `sort` переставляет исходный массив, и
  // отсортированный реестр тихо поменял бы порядок у всех остальных его
  // читателей — от отрисовки до подбора по клику.
  //
  // Вычитание, а не сравнение через `<`: с Infinity (предмет не попал в
  // кадр) разность даёт NaN, а NaN в компараторе оставляет порядок
  // неопределённым. Поэтому равенство разбирается отдельно и явно.
  return [...items].sort((a, b) => {
    const ax = screenX(a)
    const bx = screenX(b)
    if (ax === bx) return 0
    return ax < bx ? -1 : 1
  })
}
