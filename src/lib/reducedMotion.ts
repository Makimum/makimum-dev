/**
 * Просьба уменьшить движение — один источник правды на всю комнату.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ `matchMedia` НА МЕСТЕ. Раньше каждый
 * предмет спрашивал систему сам, ОДИН РАЗ при сборке. Из этого следовали
 * две вещи, и обе плохие:
 *
 *  1. Переключение настройки в системе не перезагружает страницу. Человек,
 *     которому стало плохо от движения, включал «уменьшить движение» — и
 *     комната продолжала двигаться до тех пор, пока он не догадается
 *     обновить вкладку. Ровно тот случай, когда настройка нужна СЕЙЧАС.
 *  2. Три копии одной строки в трёх файлах рано или поздно разъезжаются.
 *
 * Здесь запрос один, ответ живой, и подписаться на смену может кто угодно.
 *
 * ЭТО НЕ ВЫКЛЮЧАТЕЛЬ, А СТУПЕНИ. Сигнал говорит «мне плохо от
 * вестибулярного движения», а не «уберите всю анимацию». Мгновенная смена
 * состояния дезориентирует не меньше: предметы телепортируются. Правило
 * по всему проекту одно — крупное перемещение и вращение убираются,
 * короткое затухание остаётся.
 */

const QUERY = '(prefers-reduced-motion: reduce)'

/** Живой ответ, а не снимок на момент загрузки. */
export function prefersReducedMotion(): boolean {
  return typeof matchMedia === 'function' && matchMedia(QUERY).matches
}

/**
 * Подписка на смену настройки. Возвращает отписку.
 *
 * Нужна тем, кто держит собственное состояние анимации: смена настройки
 * посреди движения обязана остановить его, а не доиграть.
 */
export function onReducedMotionChange(cb: (reduced: boolean) => void): () => void {
  if (typeof matchMedia !== 'function') return () => {}
  const mq = matchMedia(QUERY)
  const handler = (e: MediaQueryListEvent) => cb(e.matches)
  mq.addEventListener('change', handler)
  return () => mq.removeEventListener('change', handler)
}
