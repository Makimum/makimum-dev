import * as THREE from 'three'

/**
 * Материал сетчатого полотна для эргономичного кресла.
 *
 * Плоская тёмная панель не читается как сетка ни при каком цвете —
 * сетку выдаёт то, что сквозь неё видно. Поэтому здесь настоящая
 * перфорация: отверстия вырезаются в альфе прямо во фрагментном шейдере,
 * процедурно, без единого байта текстуры.
 *
 * Реализовано инъекцией в MeshStandardMaterial через onBeforeCompile,
 * а не отдельным ShaderMaterial: так полотно остаётся в общей системе
 * освещения three (PBR, тени, будущий лайтмап), а не выпадает из неё.
 *
 * Используется alphaTest, а не transparent: отверстия тогда действительно
 * вырезаются, корректно отбрасывают тень и не требуют сортировки по глубине.
 *
 * ПОЧЕМУ ПРЕЖНЯЯ ВЕРСИЯ ЧИТАЛАСЬ КАК МОСКИТНАЯ СЕТКА
 *
 * Она вырезала правильную решётку КРУГЛЫХ отверстий ОДНОГО шага. Это
 * буквально описание москитной сетки — тянутой или сварной, у которой
 * нити не переплетены. У тканого полотна кресла другое всё:
 *
 *  1. ЯЧЕЙКА НЕ КРУГЛАЯ. Круг получается при штамповке. Тканая ячейка —
 *     скруглённый прямоугольник: её края это сами нити. Считается через
 *     SDF скруглённого прямоугольника, а не длину вектора.
 *  2. НИТИ РАЗНОЙ ТОЛЩИНЫ. Основа несёт натяжение и толще утка, поэтому
 *     перемычки между ячейками прямоугольные, а не квадратные.
 *  3. ПЕРЕПЛЕТЕНИЕ. Нить идёт то поверх, то под, в шахматном порядке.
 *     Возмущаем НОРМАЛЬ, а не только цвет: у нити появляется объём, и
 *     полотно перестаёт быть плёнкой с дырками.
 *  4. ШАГ ДЫШИТ. У натянутого полотна натяжение неоднородно. Идеальная
 *     периодичность — второй признак штамповки после круглой дырки.
 *
 * ЧАСТОТА ЗАДАЁТСЯ ПО ДВУМ ОСЯМ ОТДЕЛЬНО, и это не педантизм. У полотен
 * кресла UV разложены на разные по размеру куски (спинка 0.44 × 0.62 м,
 * сиденье 0.48 × 0.46, подголовник 0.30 × 0.16), и один множитель на обе
 * оси давал бы ячейку, вытянутую ровно во столько раз, во сколько кусок
 * непропорционален. Число ячеек считается от МЕТРОВ панели, поэтому
 * ячейка выходит одного размера на всех трёх — как у одного рулона ткани.
 *
 * ЗАТУХАНИЕ ДЕТАЛИ. Ячейка около 3.5 мм на общем плане занимает меньше
 * пикселя, и без затухания и перфорация, и шахматка переплетения
 * превращаются в шум и муар — ровно то, за что зерно однажды уже
 * получило претензию «грязный экран». Поэтому берётся `fwidth` по
 * координате ячейки (сколько ячеек приходится на пиксель), и по нему
 * рельеф с перфорацией плавно уходят: вдали полотно становится ровным и
 * ровно настолько же темнее, насколько в нём было просвета. Это ручной
 * мип-уровень — и он же причина, по которой ячейку можно взять настоящего
 * размера, а не подгонять её под то, чтобы «издали не рябило».
 */

export interface MeshFabricOptions {
  color?: number
  /** Ячеек поперёк полотна, по всей ширине куска UV. */
  cellsU?: number
  /** Ячеек вдоль полотна. */
  cellsV?: number
  /** Полуразмер отверстия внутри ячейки вдоль основы, 0…0.5 */
  hole?: number
  /** Насколько уток тоньше основы, 0…1. Ноль — нити одинаковые. */
  weftThin?: number
  /** Глубина рельефа переплетения, 0…1 */
  weave?: number
  /** Разброс шага, доля. 0 — идеальная периодичность (признак штамповки). */
  jitter?: number
}

export function meshFabricMaterial(opts: MeshFabricOptions = {}): THREE.MeshStandardMaterial {
  const {
    color = 0x33363b,
    cellsU = 126,
    cellsV = 155,
    hole = 0.34,
    weftThin = 0.38,
    weave = 0.6,
    jitter = 0.05,
  } = opts

  const mat = new THREE.MeshStandardMaterial({
    color,
    roughness: 0.9,
    metalness: 0,
    side: THREE.DoubleSide,
    alphaTest: 0.5,
  })
  mat.shadowSide = THREE.DoubleSide

  /**
   * Доля просвета в ячейке — площадь скруглённого прямоугольника.
   * Нужна затуханию: когда перфорация перестаёт разрешаться в пиксель,
   * полотно закрывается, и потемнеть оно обязано ровно на столько,
   * сколько сквозь него было видно. Иначе сетка вдали светлеет.
   */
  const hx = hole
  const hy = hole * (1 - weftThin * 0.45)
  const r = hole * 0.45
  const openFraction = Math.min(0.95, Math.max(0, (4 * hx * hy - (4 - Math.PI) * r * r) / 1))

  mat.onBeforeCompile = (shader) => {
    shader.uniforms.uCells = { value: new THREE.Vector2(cellsU, cellsV) }
    shader.uniforms.uHole = { value: hole }
    shader.uniforms.uWeftThin = { value: weftThin }
    shader.uniforms.uWeave = { value: weave }
    shader.uniforms.uJitter = { value: jitter }
    shader.uniforms.uOpen = { value: openFraction }

    shader.vertexShader = shader.vertexShader
      .replace('#include <common>', '#include <common>\nvarying vec2 vFab;')
      .replace('#include <begin_vertex>', '#include <begin_vertex>\n  vFab = uv;')

    shader.fragmentShader = shader.fragmentShader
      .replace(
        '#include <common>',
        `#include <common>
varying vec2 vFab;
uniform vec2 uCells;
uniform float uHole;
uniform float uWeftThin;
uniform float uWeave;
uniform float uJitter;
uniform float uOpen;

// Расстояние до скруглённого прямоугольника. Именно эта форма отличает
// тканую ячейку от штампованной круглой дырки.
float sdRoundBox(vec2 p, vec2 b, float rad) {
  vec2 q = abs(p) - b + rad;
  return min(max(q.x, q.y), 0.0) + length(max(q, 0.0)) - rad;
}

// Детерминированный шум по номеру ячейки: одна и та же сетка при каждой
// сборке. Без синуса — его точность на разных GPU гуляет, и сетка
// начинала бы мерцать от кадра к кадру.
float cellNoise(vec2 c) {
  vec3 p = fract(vec3(c.xyx) * 0.1031);
  p += dot(p, p.yzx + 33.33);
  return fract((p.x + p.y) * p.z);
}`,
      )
      .replace(
        '#include <alphamap_fragment>',
        `#include <alphamap_fragment>
  vec2 fp = vFab * uCells;

  // Сколько ячеек приходится на пиксель. Отсюда — можно ли вообще
  // рисовать плетение, или на этом расстоянии оно уже шум.
  float perPixel = max(fwidth(fp.x), fwidth(fp.y));
  float detail = 1.0 - smoothstep(0.30, 0.80, perPixel);

  vec2 cellId = floor(fp);
  vec2 cell = fract(fp) - 0.5;

  // Шаг дышит. Смещение в единицы процентов ячейки: идеальная
  // периодичность читается как штамповка, а не как ткань.
  cell += (vec2(cellNoise(cellId), cellNoise(cellId + 7.3)) - 0.5) * uJitter;

  // Отверстие уже поперёк основы ровно настолько, насколько уток тоньше:
  // тонкая нить оставляет больше просвета.
  // Имя не half: это зарезервированное слово GLSL, и шейдер с ним
  // не собирается — а собирается он в рантайме, то есть молча.
  vec2 holeHalf = vec2(uHole, uHole * (1.0 - uWeftThin * 0.45));
  float d = sdRoundBox(cell, holeHalf, uHole * 0.45);

  // fwidth даёт ширину одного пикселя в единицах d — отсюда стабильное
  // сглаживание на любом удалении, без муара на дальнем плане.
  float w = max(fwidth(d), 1e-5);
  float holeMask = (1.0 - smoothstep(-w, w, d)) * detail;
  diffuseColor.a *= 1.0 - holeMask;

  // Закрываясь вдали, полотно обязано потемнеть на ту же долю, на
  // которую сквозь него было видно, — иначе сетка издали светлеет.
  diffuseColor.rgb *= mix(1.0 - uOpen, 1.0, detail);

  // Переплетение в шахматном порядке: где основа сверху, там уток снизу.
  // Знак нужен и цвету, и нормали ниже, поэтому считается один раз.
  float over = (mod(cellId.x + cellId.y, 2.0) * 2.0 - 1.0) * detail;
  // Нить, лежащая сверху, ловит больше света — но разница у чёрной нити
  // небольшая: тёмное полотно светлеет от геометрии, а не от цвета.
  diffuseColor.rgb *= 1.0 + over * uWeave * 0.09;`,
      )
      .replace(
        '#include <normal_fragment_maps>',
        `#include <normal_fragment_maps>
  {
    // Объём нити. Без этого полотно остаётся плёнкой с дырками: свет
    // ложится на него ровно, и вблизи это первое, что выдаёт подделку.
    //
    // Скат считается от края отверстия внутрь перемычки: у самой дырки
    // нить круче всего заваливается, к середине перемычки выполаживается.
    // Направление ската — градиент того же SDF, взятый производными,
    // поэтому он бесплатен и всегда согласован с формой ячейки.
    vec2 grad = vec2(dFdx(d), dFdy(d));
    float g = length(grad);
    if (g > 1e-6) {
      float ridge = clamp(-d / max(uHole * 0.9, 1e-4), 0.0, 1.0);
      // Поперёк нити нормаль заваливается сильнее к краю (1 − ridge),
      // а знак over разводит основу и уток по высоте. Множитель detail
      // в нём уже сидит, поэтому вдали рельеф уходит вместе с плетением.
      float bend = uWeave * (1.0 - ridge) * 0.55;
      normal = normalize(normal - normalize(vec3(grad / g, 0.0)) * bend * over);
    }
  }`,
      )
  }

  // Без своего ключа three переиспользует программу обычного
  // MeshStandardMaterial и инъекция молча не применится.
  mat.customProgramCacheKey = () =>
    `meshFabric:${cellsU}:${cellsV}:${hole}:${weftThin}:${weave}:${jitter}`

  return mat
}
