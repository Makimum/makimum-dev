/**
 * Этот модуль решает одну вещь: с чего посетитель НАЧИНАЕТ — со страницы
 * или сразу с комнаты.
 *
 * `roomCapable()` решает только автовход, и с частью 2 это уже не то же
 * самое, что «покажем ли комнату вообще». С телефона чанк сцены теперь
 * скачивается — по кнопке «enter the room»: 317.59 КБ gzip чанка сцены едут
 * ровно тогда, когда человек их попросил, и ни байтом раньше (страница —
 * index.html + entry, около 14 КБ — приезжает всегда, см. `FACTS.bundleKB`).
 * Отказ автовхода означает не
 * «комнаты не будет», а «комната не поедет сама»: тому, кто кнопку не
 * нажал, страница из `src/page/*` служит вместо неё, а не заглушкой.
 *
 * Почему автовхода на телефоне нет: WebGL-сцена там не «просто мельче» —
 * она греет батарею, съедает память и показывает ультраширокий монитор
 * шириной в палец. Платить этим по факту открытия ссылки нельзя; платить
 * по нажатию — можно, и человек знает, за что платит.
 *
 * ЕДИНСТВЕННОЕ ПРАВИЛО ГЕЙТА живёт здесь, в `roomCapable()`. В CSS его нет
 * — оно только приезжает в разметку значением `data-mode` на `<html>`,
 * которое ставит один писатель, `setMode()` из этого же файла. Разметка
 * реагирует на `data-mode`, а не пересчитывает условие сама: два места,
 * решающие «мобильный ли это», — верный способ получить страницу, где
 * решения расходятся.
 *
 * ЕДИНСТВЕННЫЕ ПИСАТЕЛИ `data-mode` после старта — `enterRoom()` и
 * `leaveRoom()` в `entry.ts`. Отдельные функции, а не голый `setMode()`,
 * потому что переключение режима означает ещё и «покажи холст в настоящем
 * размере» (это делает `main.ts`, у которого есть рендерер) и «верни
 * страницу на ту же позицию скролла». Держать эту связь в двух местах
 * значит однажды показать комнату в буфере 300 × 150.
 */

/** Ниже этой ширины ультраширокий монитор нечитаем даже в фокусе. */
export const ROOM_MIN_WIDTH = 900
/** Ландшафтная щель браузера на телефоне бывает шире 900, но ниже 480. */
export const ROOM_MIN_HEIGHT = 480

export type Mode = 'page' | 'room'

/**
 * Основное указательное устройство — палец: планшет или телефон. Ноутбук с
 * сенсорным экраном сюда не попадает, у него primary — трекпад.
 *
 * Отдельная экспортируемая функция, а не второй `matchMedia` по месту:
 * решатель «мобильный ли это» остаётся ОДИН, просто получает имя. Кроме
 * `roomCapable()` его спрашивает слушатель `resize` в `entry.ts` — там
 * важен не гейт целиком, а ровно эта его половина.
 */
export function coarsePointer(): boolean {
  return matchMedia('(pointer: coarse)').matches
}

/**
 * Бережный рендер: экономим БАТАРЕЮ, а не пиксели.
 *
 * Ответ тот же, что давал прежний `mobile` в `main.ts`, — качество кадра не
 * меняется ни на одном устройстве. Функция заведена ради другого: у вопроса
 * «мобильный ли это» перестаёт быть два читателя. `main.ts` держал свой
 * `matchMedia` в обход этого модуля, при том что комментарий наверху файла
 * утверждает обратное — а два решателя однажды разойдутся.
 */
export function thriftyRender(): boolean {
  return coarsePointer()
}

/**
 * Самый мелкий повторяющийся кегль в документах, в пикселях холста монитора.
 * Холст 2048 × 870, масштаб в `paint.ts` — `k = H / 870`, то есть на мониторе
 * ровно единица: числа кеглей там и есть пиксели холста.
 */
const SMALLEST_TYPE_PX = 19

/**
 * Ниже этого экранного кегля документ на полотне читать нельзя.
 *
 * Десктоп 1440 × 900 сегодня даёт 11.3 px и считается нормой. Взято 10 —
 * ниже с запасом, но в ПУСТОЙ полосе: между телефоном в ландшафте (4.9) и
 * iPad 11" в ландшафте (10.5) реальных устройств нет, и любой порог между
 * ними классифицирует всю технику одинаково. Замер:
 * `scripts/measure-readability.mjs`.
 */
const MIN_TYPE_PX = 10

/**
 * Насколько полотну позволено торчать за края кадра.
 *
 * Строгое «не шире кадра» выкинуло бы iPad 13" в ландшафте: там полотно шире
 * на ВОСЕМЬ пикселей из 1374, то есть на 0.6% — это край рамки, а не
 * потерянный текст (восемь экранных пикселей — это двенадцать пикселей
 * холста из 2048, они целиком лежат в собственных полях документа).
 *
 * Полоса снова пустая, как и у кегля: следующий по величине промах — iPad в
 * портрете, и там полотно шире кадра на 92%. Между 0.6% и 92% реальных
 * устройств нет, так что точность этого числа ни на что не влияет.
 */
const WIDTH_TOLERANCE = 1.05

export interface PanelFit {
  /** Экранный кегль самого мелкого текста документа, в CSS-пикселях. */
  typePx: number
  /** Влезает ли полотно в кадр по горизонтали, с допуском на край рамки. */
  fitsWidth: boolean
}

/**
 * Перевод спроецированного полотна в две величины, по которым принимается
 * решение. Отдельно от `documentsReadable`, чтобы арифметика проверялась
 * прогоном без браузера так же, как и само правило.
 */
export function panelFit(
  panel: { w: number; h: number },
  viewW: number,
  canvasH: number,
): PanelFit {
  return {
    typePx: (SMALLEST_TYPE_PX * panel.h) / canvasH,
    fitsWidth: panel.w <= viewW * WIDTH_TOLERANCE,
  }
}

/**
 * Годится ли этот экран для документов на мониторе. Решает РЕЕСТР предметов,
 * и только его: качество кадра — вопрос батареи, а не читаемости, и у iPad
 * ответы на них разные.
 *
 * Условие двойное, и второе половина не менее важна первой. Полотно
 * ультраширокое: в портрете оно не влезает по горизонтали — 1602 CSS px в
 * окно шириной 834, то есть половина документа за кадром. Панорамирования в
 * комнате нет, а отодвинуть камеру нельзя: кегль делится на тот же
 * множитель и падает до нечитаемого.
 *
 * `null` — это «посчитать не удалось», и тогда ответ ДА: отнимать предметы
 * из-за собственной неуверенности неправильно, а не посчитаться проекция
 * может ровно в одном случае — сцена ещё не собралась.
 */
export function documentsReadable(fit: PanelFit | null): boolean {
  if (!fit) return true
  return fit.typePx >= MIN_TYPE_PX && fit.fitsWidth
}

/**
 * Что кликабельно. Вынесено чистой функцией, потому что это единственное
 * место, где решается доступность предметов, — и оно обязано проверяться
 * прогоном, а не разглядыванием комнаты.
 *
 * Там, где документы не читаются, остаются предметы, срабатывающие НА МЕСТЕ:
 * подлетать к нечитаемому полотну незачем. Побочная выгода не косметическая:
 * `createFocus` строит BVH по каждому мешу своего реестра, а монитор с
 * ноутбуком — самые тяжёлые узлы сцены.
 */
export function pickHotspots<T extends { kind?: string }>(readable: boolean, all: T[]): T[] {
  if (readable) return all
  return all.filter((h) => h.kind === 'switch' || h.kind === 'spin')
}

export function roomCapable(): boolean {
  // Палец проверяется ПЕРВЫМ, потому что этот ответ не зависит от раскладки
  // и потому остаётся верным даже там, где размеры ещё не известны.
  if (coarsePointer()) return false

  // НОЛЬ — ЭТО «ЕЩЁ НЕ ЗНАЮ», А НЕ «ТЕЛЕФОН». Замер бывает нулевым, если
  // модуль исполнился до раскладки страницы или вкладка восстановилась из
  // фона. Прежний код читал такой ноль как узкий экран, и десктоп попадал
  // в лобби — а выйти оттуда мог только по событию `resize`: `ResizeObserver`
  // в лобби молчит, потому что у `#scene` там `display: none` и коробки
  // просто нет. Поймано в браузере на перезагрузке.
  const w = window.innerWidth || document.documentElement.clientWidth
  const h = window.innerHeight || document.documentElement.clientHeight
  if (!w || !h) return true

  if (w < ROOM_MIN_WIDTH) return false
  if (h < ROOM_MIN_HEIGHT) return false
  return true
}

export function setMode(mode: Mode) {
  document.documentElement.dataset.mode = mode
}

export function currentMode(): Mode {
  // По белому списку, а не «всё, что не room, это lobby». Прежнее чтение
  // схлопывало любое незнакомое значение в одно, и третье состояние в нём
  // не выживало бы вовсе — это ровно та ошибка, из-за которой у атрибута
  // появляется второй писатель.
  return document.documentElement.dataset.mode === 'room' ? 'room' : 'page'
}

/** Тот же вопрос, что и `currentMode() === 'room'`, но по имени: читают
 *  его в `main.ts`, где важен не «какой режим», а «идёт ли кадровый цикл». */
export function isRoomOpen(): boolean {
  return currentMode() === 'room'
}
